"""Generate the cosine-sim distribution figure for the paper (main or appendix).

Main (default):
  Layout (figure*, full page width):
  • Row 1 : PTC-FR  — combined | GT | sigma-MAP
  • Row 2 : PTC-FM  — combined | GT | sigma-MAP

Appendix (--appendix):
  Layout (figure*[p], full page width):
  • Combined legend at top
  • 16 rows: 4 datasets × 4 clusters — combined_noleg | gt_noleg | sigma-MAP
    (legend-free plots generated by cosim_dist_plot.py --no-legend)

Cosim dist filenames (from cosim_dist_plot.py):
  cosim_{ds}_K={K}_ratio={r}_cluster{cl}_combined_{augnet}.pdf
  cosim_{ds}_K={K}_ratio={r}_cluster{cl}_combined_{augnet}_noleg.pdf  (--no-legend)
  cosim_{ds}_K={K}_ratio={r}_cluster{cl}_gt_{augnet}.pdf
  cosim_{ds}_K={K}_ratio={r}_cluster{cl}_gt_{augnet}_noleg.pdf        (--no-legend)

Sigma-MAP filenames (from plot_sigma_map.py):
  sigma_map_{ds}_cl{cluster}.pdf

Usage
-----
python -B scripts/latex/make_cosim_dist_figure.py \\
    --augnet AugMap_CEMax_Symm_SameModelPerD_Minus_Short_SameLinearPerD \\
    --cluster 1 \\
    --out attic/cosim_dist_figure.tex

python -B scripts/latex/make_cosim_dist_figure.py --appendix \\
    --augnet AugMap_CEMax_Symm_SameModelPerD_Minus_Short_SameLinearPerD \\
    --out attic/cosim_dist_figure.tex
"""

import argparse
from pathlib import Path


DATASETS      = ["ptc_fr", "ptc_fm"]
DATASETS_ALL  = ["ptc_fr", "ptc_fm", "ptc_mr", "cox2"]
CLUSTERS_ALL  = [1, 2, 3, 4]
DS_NAMES      = {"ptc_fr": "PTC-FR", "ptc_fm": "PTC-FM",
                 "ptc_mr": "PTC-MR", "cox2":   "COX2"}
QCAL_LABELS   = {1: r"\Qcal_1", 2: r"\Qcal_2", 3: r"\Qcal_3", 4: r"\Qcal_4"}


# ── filename helpers ──────────────────────────────────────────────────────────

def _combined_fname(ds, K_val, ratio, cluster, augnet, noleg=False):
    sfx = "_noleg" if noleg else ""
    return f"cosim_{ds}_K={K_val}_ratio={ratio}_cluster{cluster}_combined_{augnet}{sfx}.pdf"


def _gt_fname(ds, K_val, ratio, cluster, augnet, noleg=False):
    sfx = "_noleg" if noleg else ""
    return f"cosim_{ds}_K={K_val}_ratio={ratio}_cluster{cluster}_gt_{augnet}{sfx}.pdf"


def _sigmamap_fname(ds, cluster):
    return f"sigma_map_{ds}_cl{cluster}.pdf"


# ── LaTeX generation — main figure ────────────────────────────────────────────

def make_latex(augnet, cluster, K_val, ratio, fig_dir_cosim, fig_dir_sigma_map, img_w_frac):
    img_w = f"{img_w_frac:.3f}\\linewidth"

    def inc(fig_dir, fname):
        return rf"\includegraphics[width={img_w}]{{{fig_dir}/{fname}}}"

    sigma_set = r"\{0.1, 0.5, 1, 10\}"

    lines = []
    lines.append(r"\begin{figure*}[t]")
    lines.append(r"  \centering")

    for ri, ds in enumerate(DATASETS):
        lines.append(f"  % Row {ri + 1}: {DS_NAMES[ds]}")

        imgs = [
            (fig_dir_cosim,     _combined_fname(ds, K_val, ratio, cluster, augnet)),
            (fig_dir_cosim,     _gt_fname(ds, K_val, ratio, cluster, augnet)),
            (fig_dir_sigma_map, _sigmamap_fname(ds, cluster)),
        ]

        for i, (fdir, fname) in enumerate(imgs):
            if i == 0:
                suffix = r"\hspace{0.012\linewidth}\hfill%"
            elif i < len(imgs) - 1:
                suffix = r"\hfill%"
            else:
                suffix = "%"
            lines.append(f"  {inc(fdir, fname)}{suffix}")

        if ri < len(DATASETS) - 1:
            lines.append(r"  \par\smallskip")

    sigma_set = r"\{0.1, 0.5, 1, 10\}"
    lines.append(r"  \caption{%")
    lines.append(
        r"    Cosine similarity distributions of positive and negative pairs selected by"
        "\n"
        r"    \our at $\budget=40$, computed in the $f_\phi$ output space"
        "\n"
        r"    ($\zbphi$--$\xbphi$ inner products), and the resulting test MAP as a"
        "\n"
        r"    function of noise $\sigma$. Rows show results for \textbf{PTC-FR} and"
        "\n"
        r"    \textbf{PTC-FM} ($\Qcal_1$). Each row shows (left to right): all four"
        "\n"
        f"    noise levels $\\sigma \\in {sigma_set}$ overlaid (distinct colour"
        "\n"
        r"    per $\sigma$ for positive pairs; red: negative pairs), the"
        "\n"
        r"    ground-truth distribution, and the $\sigma$--MAP curve."
    )
    lines.append(r"  }")
    lines.append(r"  \label{fig:cosim_dist_main}")
    lines.append(r"\end{figure*}")

    return "\n".join(lines)


# ── LaTeX generation — appendix figure ───────────────────────────────────────

def _appendix_dataset_figure(ds, ds_idx, augnet, K_val, ratio,
                              fig_dir_cosim, fig_dir_sigma_map, img_w_frac):
    """One figure*[p] for a single dataset (4 cluster rows + legend at top)."""
    img_w   = f"{img_w_frac:.3f}\\linewidth"
    label_w = "0.06\\linewidth"
    row_gap = r"  \par\vspace{2pt}"
    sigma_set = r"\{0.1, 0.5, 1, 10\}"

    def inc(fig_dir, fname):
        return rf"\includegraphics[width={img_w}]{{{fig_dir}/{fname}}}"

    lines = []
    lines.append(r"\begin{figure*}[p]")
    lines.append(r"  \centering")

    # Legend at top of every page
    lines.append(
        rf"  \includegraphics[width=0.40\linewidth]{{{fig_dir_cosim}/cosim_color_legend.pdf}}"
    )
    lines.append(r"  \par\medskip")

    for ci, cl in enumerate(CLUSTERS_ALL):
        qcal = QCAL_LABELS[cl]
        row_label = rf"\makebox[{label_w}][r]{{\small${qcal}$\,}}%"

        imgs = [
            (fig_dir_cosim,     _combined_fname(ds, K_val, ratio, cl, augnet, noleg=True)),
            (fig_dir_cosim,     _gt_fname(ds, K_val, ratio, cl, augnet, noleg=True)),
            (fig_dir_sigma_map, _sigmamap_fname(ds, cl)),
        ]

        for i, (fdir, fname) in enumerate(imgs):
            if i == 0:
                lines.append(f"  {row_label}")
                lines.append(f"  {inc(fdir, fname)}\\hspace{{0.012\\linewidth}}\\hfill%")
            elif i < len(imgs) - 1:
                lines.append(f"  {inc(fdir, fname)}\\hfill%")
            else:
                lines.append(f"  {inc(fdir, fname)}%")

        if ci < len(CLUSTERS_ALL) - 1:
            lines.append(row_gap)

    lines.append(r"  \caption{%")
    lines.append(
        rf"    $\augnetscore$ score distributions for \textbf{{{DS_NAMES[ds]}}}."
        "\n"
        r"    Positive and negative pairs selected by \our at $\budget=40$,"
        "\n"
        r"    computed in the $f_\phi$ output space ($\zbphi$--$\xbphi$ inner products)."
        "\n"
        r"    Rows correspond to $\Qcal_1$ to $\Qcal_4$."
        "\n"
        r"    Each row shows (left to right): all four noise levels"
        "\n"
        f"    $\\sigma \\in {sigma_set}$ overlaid (see legend; distinct colour"
        "\n"
        r"    per $\sigma$ for positive pairs; red: negative pairs), the"
        "\n"
        r"    ground-truth distribution, and the $\sigma$--MAP curve."
    )
    lines.append(r"  }")
    lines.append(rf"  \label{{fig:cosim_dist_{ds}}}")
    lines.append(r"\end{figure*}")

    return "\n".join(lines)


def make_appendix_latex(augnet, K_val, ratio, fig_dir_cosim, fig_dir_sigma_map, img_w_frac):
    return "\n\n".join(
        _appendix_dataset_figure(ds, ri, augnet, K_val, ratio,
                                 fig_dir_cosim, fig_dir_sigma_map, img_w_frac)
        for ri, ds in enumerate(DATASETS_ALL)
    )


# ── main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(
        description="Generate LaTeX figure* snippet for cosim distribution + sigma-MAP plots."
    )
    parser.add_argument("--augnet", type=str,
                        default="AugMap_CEMax_Symm_SameModelPerD_Minus_Short_SameLinearPerD")
    parser.add_argument("--cluster", type=int, default=1,
                        help="Which cluster's cosim plots to use (default: 1; main figure only)")
    parser.add_argument("--K-val",  type=int,   default=40)
    parser.add_argument("--ratio",  type=float, default=0.13)
    parser.add_argument("--fig-dir-cosim",      type=str, default=None,
                        help="Overleaf path for cosim dist PDFs (default depends on --appendix)")
    parser.add_argument("--fig-dir-sigma-map",  type=str, default=None,
                        help="Overleaf path for sigma-MAP PDFs (default depends on --appendix)")
    parser.add_argument("--img-width", type=float, default=0.30,
                        help="Per-image width as fraction of \\linewidth (default: 0.30 main, 0.28 appendix)")
    parser.add_argument("--appendix", action="store_true",
                        help="Generate appendix figure (4 datasets × 4 clusters)")
    parser.add_argument("--out",    type=str,   default="attic/cosim_dist_figure.tex")
    args = parser.parse_args()

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    if args.appendix:
        fig_dir_cosim     = args.fig_dir_cosim     or "FIG/appendix/cos_sim_dist"
        fig_dir_sigma_map = args.fig_dir_sigma_map or "FIG/appendix/sigma_map"
        img_w = args.img_width if args.img_width != 0.30 else 0.28
        tex = make_appendix_latex(
            augnet=args.augnet,
            K_val=args.K_val,
            ratio=args.ratio,
            fig_dir_cosim=fig_dir_cosim,
            fig_dir_sigma_map=fig_dir_sigma_map,
            img_w_frac=img_w,
        )
        app_path = out_path.with_stem(out_path.stem + "_appendix")
        app_path.write_text(tex + "\n")
        print(f"Appendix LaTeX written to {app_path}")
        print()
        print(tex)
    else:
        fig_dir_cosim     = args.fig_dir_cosim     or "FIG/cos_sim_dist"
        fig_dir_sigma_map = args.fig_dir_sigma_map or "FIG/sigma_map"
        tex = make_latex(
            augnet=args.augnet,
            cluster=args.cluster,
            K_val=args.K_val,
            ratio=args.ratio,
            fig_dir_cosim=fig_dir_cosim,
            fig_dir_sigma_map=fig_dir_sigma_map,
            img_w_frac=args.img_width,
        )
        out_path.write_text(tex + "\n")
        print(f"LaTeX written to {out_path}")
        print()
        print(tex)


if __name__ == "__main__":
    main()
